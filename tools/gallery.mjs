// Writes the galleries GitHub shows: the repository README (every kit), one README per kit (its
// samples by category, as a grid of thumbnails) and one README per sample (its build, features,
// steps and checks). All three are generated; edit showcase.yaml and this file instead.

import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";

import { KITS, ROOT, byKitOrder } from "./kits.mjs";
import { loadSamples } from "./samples.mjs";

const COLUMNS = 3;
const GENERATED = "<!-- Generated by tools/gallery.mjs from showcase.yaml and build.json; do not edit. -->";

const escape = (text) => String(text ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const anchor = (text) => text.toLowerCase().replace(/[^\p{L}\p{N} -]/gu, "").trim().replace(/ /g, "-");
const kb = (bytes) => (bytes >= 1024 * 1024 ? `${(bytes / 1024 / 1024).toFixed(1)} MB` : `${Math.max(1, Math.round(bytes / 1024))} KB`);

function card(sample, from) {
  const link = path.relative(from, sample.dir).split(path.sep).join("/");
  const image = sample.build ? `<a href="${link}/"><img src="${link}/thumb.png" alt="${escape(sample.title)}" width="100%"></a><br>` : "<i>not built yet</i><br>";
  const tags = sample.tags.map((tag) => `<code>${escape(tag)}</code>`).join(" ");
  return [
    `<td width="${Math.floor(100 / COLUMNS)}%" valign="top">`,
    image,
    `<sub>${KITS[sample.kit].title}${sample.preview ? " · ▶ animated" : ""}</sub><br>`,
    `<b><a href="${link}/">${escape(sample.title)}</a></b><br>`,
    `<sub>${escape(sample.summary)}</sub><br>`,
    sample.build ? `<sub><i>${escape(sample.build.stats)}</i></sub><br>` : "",
    tags,
    "</td>",
  ].join("\n");
}

function grid(samples, from) {
  const rows = [];
  for (let i = 0; i < samples.length; i += COLUMNS) {
    const cells = samples.slice(i, i + COLUMNS).map((sample) => card(sample, from));
    while (cells.length < COLUMNS) cells.push(`<td width="${Math.floor(100 / COLUMNS)}%"></td>`);
    rows.push(`<tr>\n${cells.join("\n")}\n</tr>`);
  }
  return `<table>\n${rows.join("\n")}\n</table>`;
}

function byCategory(samples) {
  const groups = new Map();
  for (const sample of samples) {
    if (!groups.has(sample.category)) groups.set(sample.category, []);
    groups.get(sample.category).push(sample);
  }
  return [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function kitReadme(kit, samples) {
  const dir = path.join(ROOT, kit);
  const groups = byCategory(samples);
  const tags = new Map();
  for (const sample of samples) for (const tag of sample.tags) tags.set(tag, (tags.get(tag) ?? 0) + 1);
  const features = new Set(samples.flatMap((sample) => sample.features));
  return [
    GENERATED,
    `# ${KITS[kit].title} showcase`,
    "",
    `${KITS[kit].tagline} Every sample is built from \`showcase.yaml\` by the kit's own commands and drawn by its own engine (\`${KITS[kit].repo}\`).`,
    "",
    `**${samples.length} samples** · ${groups.length} categories · ${features.size} features of \`${KITS[kit].repo}/features.yaml\` · [all kits](../README.md)`,
    "",
    groups.map(([category, list]) => `[${category}](#${anchor(category)}) (${list.length})`).join(" · "),
    "",
    ...groups.flatMap(([category, list]) => [`## ${category}`, "", grid(list, dir), ""]),
    "## Tags",
    "",
    [...tags.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([tag, n]) => `\`${tag}\` ${n}`).join(" · "),
    "",
  ].join("\n");
}

function rootReadme(all) {
  const built = Object.keys(KITS).filter((kit) => all.some((sample) => sample.kit === kit));
  const kits = [...built].sort(byKitOrder);
  const featured = built.flatMap((kit) => all.filter((sample) => sample.kit === kit && sample.featured)).slice(0, 9);
  const table = kits.map((kit) => {
    const samples = all.filter((sample) => sample.kit === kit);
    const cover = samples.find((sample) => sample.featured && sample.build) ?? samples.find((sample) => sample.build);
    const image = cover ? `<a href="${kit}/"><img src="${kit}/${cover.slug}/thumb.png" width="200"></a>` : "";
    return `| ${image} | **[${KITS[kit].title}](${kit}/)** | ${samples.length} | ${byCategory(samples).length} | ${KITS[kit].tagline} |`;
  });
  return [
    GENERATED,
    "# Kition Showcase",
    "",
    "Kition Showcase: sample files for every kit, built with the kits' own commands and rendered by their own engines.",
    "",
    "[Kition](https://kition.ai) · [Developer docs](https://developer.kition.ai)",
    "",
    "Each sample is a `showcase.yaml`: a list of the kit's own engine commands, and checks on what they must produce. `tools/build.mjs` runs them through the kit, which saves the document and renders its thumbnail itself, so the gallery shows exactly what Kition draws.",
    "",
    "The samples double as tests: `node tools/build.mjs --check` rebuilds every sample against the kits' current code and fails when a thumbnail moves beyond the render tolerance or a check fails.",
    "",
    `**${all.length} samples** in ${kits.length} kits.` + " The same gallery as a static website for https://kition.ai/showcase, a page per kit and per sample (search, filters, downloads): `node tools/site.mjs` builds it into `dist/`.",
    "",
    "| | Kit | Samples | Categories | |",
    "|---|---|---:|---:|---|",
    ...table,
    "",
    ...(featured.length ? ["## Featured", "", grid(featured, ROOT), ""] : []),
    "## Build and test",
    "",
    "```sh",
    "pnpm install",
    "node tools/build.mjs                 # build every sample and the galleries",
    "node tools/build.mjs film/          # one kit, or one sample: photo/autumn-poster",
    "node tools/build.mjs --check         # rebuild into a temporary folder and compare",
    "```",
    "",
    "The kits are expected next to this repository (`../kition-film`, `../kition-photo`, …; or set `KITION_ROOT`), with fonts from `../kition-fonts`. See [CONTRIBUTING.md](CONTRIBUTING.md) for the sample format.",
    "",
    "## License",
    "",
    "The tooling is Apache-2.0 ([LICENSE](LICENSE)). The sample files are original works, made with the kits' own commands; you are free to use them under the same license.",
    "",
  ].join("\n");
}

function describeCheck(entry) {
  return Object.entries(entry.values ?? {}).map(([where, spec]) => `- \`${entry.actual ?? "inspect"}.${where}\`: \`${JSON.stringify(spec)}\``);
}

export function renderSampleReadme(sample, build) {
  const kit = KITS[sample.kit];
  const picture = sample.preview ? `![${sample.title}](preview.webp)\n\n<sub>Animated preview: ${sample.preview.from ?? 0}–${sample.preview.to} s, ${build.preview.frames} frames rendered by Kition ${kit.title}. Still: [thumb.png](thumb.png)</sub>` : `![${sample.title}](thumb.png)`;
  const checks = (sample.expected ?? []).flatMap(describeCheck);
  checks.push(`- diagnostics: ${sample.diagnostics?.length ? sample.diagnostics.map((code) => `\`${code}\``).join(", ") : "none (the kit's check finds nothing wrong)"}`);
  checks.push("- the saved document opens again; the thumbnail matches `thumb.png` within the `render` tolerance");
  const steps = YAML.stringify(sample.steps, { lineWidth: 0 }).trimEnd();
  return [
    GENERATED,
    `# ${sample.title}`,
    "",
    `[${kit.title}](../README.md) › [${sample.category}](../README.md#${anchor(sample.category)}) · ${sample.tags.map((tag) => `\`${tag}\``).join(" ")}`,
    "",
    sample.summary,
    "",
    picture,
    "",
    "| | |",
    "|---|---|",
    `| Document | [${build.document.name}](${build.document.name}) (${kb(build.document.bytes)}) |`,
    `| Contents | ${build.stats} |`,
    `| Features | ${sample.features.map((feature) => `\`${feature}\``).join(", ")} |`,
    `| Built by | \`${build.kit.repo}\` @ \`${build.kit.commit}\`${build.kit.dirty ? " (uncommitted changes)" : ""}: ${build.commands} commands in ${build.built_ms} ms |`,
    "",
    ...(sample.description ? ["## About", "", sample.description.trim(), ""] : []),
    "## Checks",
    "",
    ...checks,
    "",
    "## Steps",
    "",
    `<details><summary>${build.commands} commands (from <a href="showcase.yaml">showcase.yaml</a>${sample.prelude ? `, after the <code>${sample.prelude}</code> prelude` : ""})</summary>`,
    "",
    "```yaml",
    steps,
    "```",
    "",
    "</details>",
    "",
  ].join("\n");
}

export function writeGalleries() {
  const all = loadSamples();
  for (const kit of Object.keys(KITS)) {
    const samples = all.filter((sample) => sample.kit === kit);
    if (samples.length) fs.writeFileSync(path.join(ROOT, kit, "README.md"), kitReadme(kit, samples));
  }
  fs.writeFileSync(path.join(ROOT, "README.md"), rootReadme(all));
}

if (import.meta.url === `file://${process.argv[1]}`) writeGalleries();
